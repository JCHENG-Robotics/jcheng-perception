#!/usr/bin/env bash
# Install the laptop GPU detector as systemd user units.
#
# Run as the operator user (not root):
#
#   bash install-laptop-gpu.sh              # install + enable + start
#   bash install-laptop-gpu.sh --no-start   # install + enable only
#   bash install-laptop-gpu.sh --uninstall  # remove units/scripts
#
# The unit consumes the Pi edge uplinks on ROS domain 0 with CycloneDDS and
# runs YOLO on the local GPU.  It never opens a camera device on the robot and
# never commands motion.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
UNIT_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
LIB_DIR="$HOME/.local/lib/jcheng-perception"
CONF_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/jcheng-perception"
STATE_DIR="${XDG_STATE_HOME:-$HOME/.local/state}/jcheng-perception"
UNITS=(
    jcheng-perception-gpu.service
    jcheng-perception-gpu-alert@.service
    jcheng-perception-gpu-watchdog.service
    jcheng-perception-status.service
)
TIMERS=(jcheng-perception-status.timer)
SCRIPTS=(gpu-run.sh gpu-alert.sh gpu-watchdog-run.sh)
PY_SCRIPTS=(gpu-watchdog.py jcheng-perception-status.py)

START=1
UNINSTALL=0
for arg in "$@"; do
    case "$arg" in
        --no-start) START=0 ;;
        --uninstall) UNINSTALL=1 ;;
        -h|--help) sed -n '2,16p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "unknown argument: $arg" >&2; exit 2 ;;
    esac
done

[[ $EUID -ne 0 ]] || {
    echo "run as the operator user, not root (systemctl --user is per-user)" >&2
    exit 1
}

if [[ "$UNINSTALL" == "1" ]]; then
    systemctl --user disable --now \
        jcheng-perception-status.timer \
        jcheng-perception-gpu-watchdog.service \
        jcheng-perception-gpu.service 2>/dev/null || true
    systemctl --user reset-failed 'jcheng-perception-*' 2>/dev/null || true
    for unit in "${UNITS[@]}" "${TIMERS[@]}"; do
        rm -f "${UNIT_DIR}/${unit}"
    done
    for script in "${SCRIPTS[@]}"; do
        rm -f "${LIB_DIR}/${script}"
    done
    for script in "${PY_SCRIPTS[@]}"; do
        rm -f "${LIB_DIR}/${script}"
    done
    rmdir "$LIB_DIR" 2>/dev/null || true
    systemctl --user daemon-reload
    echo "kept ${CONF_DIR}/ and ${STATE_DIR}/"
    exit 0
fi

for script in "${SCRIPTS[@]}"; do
    bash -n "${HERE}/${script}" || { echo "syntax error in ${script}" >&2; exit 1; }
done
for script in "${PY_SCRIPTS[@]}"; do
    python3 -m py_compile "${HERE}/${script}" || {
        echo "syntax error in ${script}" >&2
        exit 1
    }
done

install -d -m 0755 "$UNIT_DIR" "$LIB_DIR" "$CONF_DIR" "$STATE_DIR"
for script in "${SCRIPTS[@]}"; do
    install -m 0755 "${HERE}/${script}" "${LIB_DIR}/${script}"
done
for script in "${PY_SCRIPTS[@]}"; do
    install -m 0755 "${HERE}/${script}" "${LIB_DIR}/${script}"
done
for unit in "${UNITS[@]}" "${TIMERS[@]}"; do
    install -m 0644 "${HERE}/${unit}" "${UNIT_DIR}/${unit}"
done

# Keep operator edits after the first install.
if [[ -f "${CONF_DIR}/gpu_laptop.yaml" ]]; then
    echo "keeping existing ${CONF_DIR}/gpu_laptop.yaml"
else
    install -m 0644 "${HERE}/gpu_laptop.yaml" "${CONF_DIR}/gpu_laptop.yaml"
fi
if [[ -f "${CONF_DIR}/cyclonedds-laptop.xml" ]]; then
    echo "keeping existing ${CONF_DIR}/cyclonedds-laptop.xml"
else
    install -m 0644 "${HERE}/cyclonedds-laptop.xml" \
        "${CONF_DIR}/cyclonedds-laptop.xml"
fi
if [[ -f "${CONF_DIR}/gpu.env" ]]; then
    echo "keeping existing ${CONF_DIR}/gpu.env"
else
    cat > "${CONF_DIR}/gpu.env" <<EOF
# Generated by install-laptop-gpu.sh. Paths are this laptop's checkout/venv.
ROS_DOMAIN_ID=0
RMW_IMPLEMENTATION=rmw_cyclonedds_cpp
CYCLONEDDS_URI=file://${CONF_DIR}/cyclonedds-laptop.xml
JCHENG_GPU_WS=${HOME}/jcheng/jcheng-perception/ros2_ws
JCHENG_GPU_CONFIG=${CONF_DIR}/gpu_laptop.yaml
JCHENG_GPU_PYTHON=${HOME}/.venvs/jcheng-perception-gpu/bin/python
# Used by jcheng-perception-status.py; override for a different robot/key.
JCHENG_ROBOT_SSH=pi@10.42.0.218
JCHENG_ROBOT_KEY=${HOME}/.ssh/id_ed25519_armpi
EOF
    chmod 0644 "${CONF_DIR}/gpu.env"
fi

echo "== preflight"
missing=0
[[ -f "${HOME}/jcheng/jcheng-perception/ros2_ws/install/setup.bash" ]] || {
    echo "WARN: missing workspace install; build jcheng_perception_gpu first" >&2
    missing=1
}
[[ -x "${HOME}/.venvs/jcheng-perception-gpu/bin/python" ]] || {
    echo "WARN: missing venv python (scripts/setup_gpu_venv.sh)" >&2
    missing=1
}
[[ -f /opt/jcheng/models/yolov8s.pt ]] || {
    echo "WARN: /opt/jcheng/models/yolov8s.pt is missing (model weights are not in the repo)" >&2
    missing=1
}
linger="$(loginctl show-user "$USER" -p Linger --value 2>/dev/null || true)"
if [[ "$linger" != "yes" ]]; then
    echo "WARN: user lingering is off; run: sudo loginctl enable-linger $USER" >&2
fi

# A running unit also contains a `laptop_gpu.launch.py` process; only treat a
# launch as "manual" when the unit itself is not active.
if systemctl --user is-active --quiet jcheng-perception-gpu.service; then
    manual=""
else
    manual="$(pgrep -f 'laptop_gpu.launch.py' | tr '\n' ' ' || true)"
fi
if [[ -n "$manual" ]]; then
    echo "WARN: a manual GPU launch is already running (pids: $manual)." >&2
    echo "      Stop it before using the unit, otherwise two detectors publish." >&2
    START=0
fi

systemctl --user daemon-reload
systemctl --user enable \
    jcheng-perception-gpu.service \
    jcheng-perception-gpu-watchdog.service \
    jcheng-perception-status.timer >/dev/null
if [[ "$START" == "1" ]]; then
    systemctl --user restart jcheng-perception-gpu.service
    systemctl --user restart jcheng-perception-gpu-watchdog.service
    # Produce a status file immediately, then let the timer refresh it.
    systemctl --user start jcheng-perception-status.service || true
    systemctl --user start jcheng-perception-status.timer
    echo "started the GPU unit, watchdog and 60 s status timer"
else
    echo "enabled but not started"
fi

echo "== status"
systemctl --user list-unit-files --no-pager 'jcheng-perception-*' || true
systemctl --user status --no-pager --lines=0 \
    jcheng-perception-gpu.service \
    jcheng-perception-gpu-watchdog.service \
    jcheng-perception-status.timer || true

cat <<'EOF'

Operate:
  systemctl --user status jcheng-perception-gpu
  systemctl --user status jcheng-perception-gpu-watchdog
  systemctl --user list-timers jcheng-perception-status.timer
  systemctl --user restart jcheng-perception-gpu
  systemctl --user stop jcheng-perception-gpu
  journalctl --user -u jcheng-perception-gpu -u jcheng-perception-gpu-watchdog -f
  cat ~/.local/state/jcheng-perception/status.txt
  cat ~/.local/state/jcheng-perception/last-alert.txt

The model is /opt/jcheng/models/yolov8s.pt (not in the repository).
The watchdog restarts the GPU unit when one camera's frames_received is frozen
for 60 s while another advances, or GpuStatus is absent for 30 s; it allows 5
restarts per 30 min and then writes last-watchdog-alert.txt. Both cameras
frozen is treated as an edge-side outage and is not restarted.
The status timer merges the robot units (over SSH) and the laptop units plus
both alert files into status.json/status.txt every 60 s.
EOF
